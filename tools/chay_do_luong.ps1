# Runs PHMN once on one configuration and appends one row to output/do_luong.csv.
#
# Every number of the real-data tables of the report comes from a row of do_luong.csv, and
# every row names its raw console log in output/runs/ and its pattern file in output/.
#
# Usage, from the project root:
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/chay_do_luong.ps1 `
#       -bo pumsb -ban cong_bo -minutil 5600000 -chu_ky 1,3000,1,2000
#
#   -bo       dataset name; the input is data/<bo>_negative.txt
#   -ban      cong_bo runs the published build (spmf.jar alone),
#             da_sua runs the corrected build (build/patched before spmf.jar),
#             def7 and duong_truoc run the two item-order variants of it (build/def7,
#             build/duong_truoc, generated by tools/sinh_thu_tu.py)
#   -minutil  the utility threshold
#   -chu_ky   minPer,maxPer,minAvg,maxAvg as one comma-separated string
#   -ghi_chu  optional free text for the ghi_chu column
#   -chay_lai run again even if the log already holds a finished run; the new run gets its own
#             files with a suffix _r2, _r3, ... so that no row of do_luong.csv loses its log
#   -han_chot optional deadline 'yyyy-MM-dd HH:mm'; a run still going at that moment is stopped,
#             the log gets a line 'STOPPED AT DEADLINE' with the CPU time used so far, no row is
#             written to do_luong.csv, and the script exits with status 3
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/chay_do_luong.ps1 `
#       -doc_log output/runs/pumsb_f_5600000.log
#
#   -doc_log  run nothing: read the four numbers back out of an existing log and print them,
#             which tests the parser on old logs (UTF-16 ones and times in E notation included)
#
# File names are output/<bo>_<o|f>_<minUtil>.txt and output/runs/<same>.log. When the four
# periodicity thresholds differ from the reference setting of the dataset (Table 8 of F0, or the
# loose setting used for chess), the name also carries them, e.g. accidents_f_19000000_p1-2000-1-1000,
# so two settings never share a log. A configuration whose log already holds a finished run is
# skipped, so a sweep that calls this script can be interrupted and started again.

[CmdletBinding(DefaultParameterSetName = 'chay')]
param(
    [Parameter(Mandatory = $true, ParameterSetName = 'chay')] [string]$bo,
    [Parameter(Mandatory = $true, ParameterSetName = 'chay')] [ValidateSet('cong_bo', 'da_sua', 'def7', 'duong_truoc')] [string]$ban,
    [Parameter(Mandatory = $true, ParameterSetName = 'chay')] [long]$minutil,
    [Parameter(Mandatory = $true, ParameterSetName = 'chay')] [string]$chu_ky,
    [Parameter(ParameterSetName = 'chay')] [string]$ghi_chu = '',
    [Parameter(ParameterSetName = 'chay')] [switch]$chay_lai,
    [Parameter(ParameterSetName = 'chay')] [string]$han_chot = '',
    [Parameter(Mandatory = $true, ParameterSetName = 'doc')] [string]$doc_log
)

function toPlainNumber([string]$raw)
{
    # Java prints a double of 10^7 or more in E notation (47663829 ms -> 4.7663829E7)
    if ($raw -match '[eE]')
    {
        $invariant = [System.Globalization.CultureInfo]::InvariantCulture
        return [double]::Parse($raw, $invariant).ToString('0.0###', $invariant)
    }
    return $raw
}

function readRunLog([string]$path)
{
    # returns the four numbers SPMF reports, or $null when the run did not finish
    $text = Get-Content $path -Raw                                 # detects the UTF-16 of old logs
    $patterns   = [regex]::Match($text, 'itemsets count : (\d+)')
    $candidates = [regex]::Match($text, 'Candidate count : (\d+)')
    $time_ms    = [regex]::Match($text, 'Time : ([\d.]+(?:[eE][-+]?\d+)?)')
    $memory_mb  = [regex]::Match($text, 'Memory ~ ([\d.]+(?:[eE][-+]?\d+)?)')
    if (-not $patterns.Success) { return $null }
    return @{
        patterns   = $patterns.Groups[1].Value
        candidates = $candidates.Groups[1].Value
        time_ms    = toPlainNumber $time_ms.Groups[1].Value
        memory_mb  = toPlainNumber $memory_mb.Groups[1].Value
    }
}

# step: parser-only mode, used to check old logs without running anything
if ($PSCmdlet.ParameterSetName -eq 'doc')
{
    $numbers = readRunLog $doc_log
    if ($null -eq $numbers)
    {
        Write-Output "$doc_log : NOT FINISHED"
        exit 1
    }
    Write-Output ("$doc_log : $($numbers.patterns) patterns, $($numbers.candidates) candidates, " +
                  "$($numbers.time_ms) ms, $($numbers.memory_mb) MB")
    exit 0
}

# step: work from the project root, never from tools/, because SPMF needs relative paths
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

# step: -File passes "1,3000,1,2000" as one string, so split it here
$thresholds = @($chu_ky -split ',' | ForEach-Object { [int]$_.Trim() })
if ($thresholds.Count -ne 4)
{
    Write-Output 'chu_ky needs four numbers: minPer, maxPer, minAvg, maxAvg'
    exit 2
}

# step: the file names follow the convention already used in output/: o = published, f = corrected,
#       d7 = item order of Definition 7, dt = positive items first
$tag = @{ 'cong_bo' = 'o'; 'da_sua' = 'f'; 'def7' = 'd7'; 'duong_truoc' = 'dt' }[$ban]

# step: the name carries the thresholds unless they are the reference setting of the dataset
$reference = @{
    'accidents' = '1,2000,5,1000'                                  # Table 8 of F0
    'pumsb'     = '1,3000,1,2000'                                  # Table 8 of F0
    'kosarak'   = '1,5000,5,5000'                                  # Table 8 of F0
    'connect'   = '1,3000,1,2000'                                  # Table 8 of F0
    'chess'     = '1,3196,1,3196'                                  # loose setting of the report
}
$stem = "$($bo)_$($tag)_$minutil"
if ($reference[$bo] -ne ($thresholds -join ','))
{
    $stem = $stem + '_p' + ($thresholds -join '-')
}

New-Item -ItemType Directory -Force -Path 'output\runs' | Out-Null

# step: skip a configuration that already finished; when asked to run it again, keep the old
#       files, since a row of do_luong.csv points to them, and write the new run beside them.
#       The test is the bare text 'itemsets count', not readRunLog, because the deliberate
#       blocking logs of pumsb 5,200,000 and 5,000,000 hold that text without any number.
if (Test-Path "output/runs/$stem.log")
{
    if ((Get-Content "output/runs/$stem.log" -Raw) -match 'itemsets count')
    {
        if (-not $chay_lai)
        {
            Write-Output "$stem : already done, skipped"
            exit 0
        }
        $k = 2
        while (Test-Path "output/runs/$($stem)_r$k.log") { $k++ }
        $stem = "$($stem)_r$k"
    }
}

$input_path = "data/$($bo)_negative.txt"
$out_path   = "output/$stem.txt"
$log_path   = "output/runs/$stem.log"
$err_path   = "$log_path.err"
$csv_path   = 'output\do_luong.csv'
$build_dir  = @{ 'da_sua' = 'build/patched'; 'def7' = 'build/def7'; 'duong_truoc' = 'build/duong_truoc' }[$ban]
$classpath  = if ($ban -eq 'cong_bo') { 'tools/spmf/spmf.jar' } else { "$build_dir;tools/spmf/spmf.jar" }

$java_args = "-Xmx6g -cp `"$classpath`" ca.pfv.spmf.gui.Main run PHMN " +
             "$input_path $out_path $minutil $($thresholds[0]) $($thresholds[1]) $($thresholds[2]) $($thresholds[3])"
$started = Get-Date
Write-Output "$stem : started $($started.ToString('HH:mm:ss dd/MM'))"

# step: optional deadline, parsed before the run so that a typo fails at once
$deadline = $null
if ($han_chot -ne '')
{
    $deadline = [datetime]::ParseExact($han_chot, 'yyyy-MM-dd HH:mm',
                                       [System.Globalization.CultureInfo]::InvariantCulture)
    Write-Output "  deadline $($deadline.ToString('HH:mm dd/MM'))"
}

# step: start without -Wait. A Process object returned by Start-Process -Wait always reports
#       TotalProcessorTime = 0, so the handle is kept alive by polling instead.
$proc = Start-Process -FilePath 'java' -ArgumentList $java_args `
    -WorkingDirectory $root -RedirectStandardOutput $log_path `
    -RedirectStandardError $err_path -NoNewWindow -PassThru

# step: `java` on PATH is a shim that runs the real JVM as a CHILD process, so the CPU time of
#       the process started above stays near 0.05 s. Find the child once with CIM, then read it
#       with the cheap Get-Process every 500 ms and keep the largest value: reading it after the
#       process has exited can fail.
$child_pid = 0
$cpu_peak = 0.0
$stopped = $false
while (-not $proc.HasExited)
{
    if ($null -ne $deadline -and (Get-Date) -gt $deadline)
    {
        # kill the shim together with the JVM it started
        & taskkill /PID $proc.Id /T /F | Out-Null
        $stopped = $true
        break
    }
    if ($child_pid -eq 0)
    {
        $children = @(Get-CimInstance Win32_Process -Filter "ParentProcessId=$($proc.Id)" `
                      -ErrorAction SilentlyContinue)
        if ($children.Count -gt 0) { $child_pid = $children[0].ProcessId }
    }
    if ($child_pid -gt 0)
    {
        try
        {
            $seconds = (Get-Process -Id $child_pid -ErrorAction Stop).TotalProcessorTime.TotalSeconds
            if ($seconds -gt $cpu_peak) { $cpu_peak = $seconds }
        }
        catch { }
    }
    Start-Sleep -Milliseconds 500
}
$proc.WaitForExit()

if ($stopped)
{
    $cpu_seconds  = [math]::Round($cpu_peak, 1)
    $wall_seconds = [math]::Round(((Get-Date) - $started).TotalSeconds, 1)
    $note = "STOPPED AT DEADLINE $han_chot : CPU $cpu_seconds s, wall $wall_seconds s, not finished"
    Add-Content -Path $log_path -Value $note -Encoding ascii
    Write-Output "$stem : $note"
    exit 3
}

$cpu_seconds  = [math]::Round($cpu_peak, 1)
$wall_seconds = [math]::Round(((Get-Date) - $started).TotalSeconds, 1)

# step: a run much longer in wall time than in CPU time was interrupted by the machine
#       sleeping; short runs are exempt because JVM start-up alone exceeds their CPU time
if ($wall_seconds -gt 60 -and $wall_seconds -gt ($cpu_seconds * 1.5))
{
    Write-Output "  WARNING: wall $wall_seconds s but CPU only $cpu_seconds s; the machine slept,"
    Write-Output "  so the Time reported by SPMF must not be used for this run"
    $sleep_note = "may ngu giua lan chay: troi $wall_seconds s, CPU $cpu_seconds s"
    if ($ghi_chu -eq '') { $ghi_chu = $sleep_note } else { $ghi_chu = "$ghi_chu; $sleep_note" }
}

# step: read the four reported numbers back out of the console text
$numbers = readRunLog $log_path
if ($null -eq $numbers)
{
    Write-Output "$stem : NOT FINISHED, see $log_path"
    exit 1
}

# step: one row per run; ascii because every value is a number or a path, and utf8 would put a
#       byte-order mark in the middle of the file on Windows PowerShell 5.1
$date = (Get-Date).ToString('yyyy-MM-dd')
$row = "$bo,$ban,$minutil,$($thresholds[0]),$($thresholds[1]),$($thresholds[2]),$($thresholds[3])," +
       "$($numbers.patterns),$($numbers.candidates),$($numbers.time_ms)," +
       "$($numbers.memory_mb),$out_path,$log_path,$date,$($ghi_chu -replace ',', ';'),$cpu_seconds"
Add-Content -Path $csv_path -Value $row -Encoding ascii

Write-Output ("$stem : $($numbers.patterns) patterns, " +
              "$($numbers.candidates) candidates, $($numbers.time_ms) ms, CPU $cpu_seconds s")
exit 0
